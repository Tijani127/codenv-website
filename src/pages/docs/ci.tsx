// Verbatim `codenv generate ci` output captured from codenv v1.1 Regina
// (802674e). Every builtin template generates this exact workflow. The \$
// escapes keep GitHub's ${{ ... }} expressions intact in a template literal.
const workflow = `# Generated by codenv. Regenerate with:
#   codenv generate ci
name: codenv

on:
  push:
    branches: [main]
  pull_request:

env:
  CODEENV_HOME: \${{ runner.temp }}\\codenv

jobs:
  codenv:
    runs-on: windows-latest
    steps:
      - uses: actions/checkout@v4

      - name: Cache Scoop buckets
        uses: actions/cache@v4
        with:
          path: \${{ runner.temp }}\\codenv\\store\\buckets
          key: codenv-buckets-v1

      - name: Cache store
        uses: actions/cache@v4
        with:
          path: \${{ runner.temp }}\\codenv\\store\\apps
          key: codenv-store-\${{ runner.arch }}-\${{ hashFiles('codenv.lock.json') }}
          restore-keys: |
            codenv-store-\${{ runner.arch }}-

      - name: Install codenv
        shell: pwsh
        run: |
          $ErrorActionPreference = 'Stop'
          $dest = "$env:CODEENV_HOME\\bin"
          New-Item -ItemType Directory -Force $dest | Out-Null
          Invoke-WebRequest -Uri "https://github.com/Tijani127/codenv/releases/latest/download/codenv-windows-\${{ runner.arch == 'X64' && 'x64' || 'arm64' }}.zip" -OutFile "$env:RUNNER_TEMP\\codenv.zip" -UseBasicParsing
          Expand-Archive "$env:RUNNER_TEMP\\codenv.zip" -DestinationPath $dest -Force
          Add-Content $env:GITHUB_PATH $dest

      - name: Prepare environment
        run: codenv install
        env:
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}

      - name: Run
        run: codenv run test
`

